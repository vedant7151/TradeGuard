CREATE TABLE portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    name VARCHAR(255) NOT NULL,
    cash_balance NUMERIC(19, 4) NOT NULL
);

CREATE TABLE positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    portfolio_id BIGINT NOT NULL,
    ticker VARCHAR(255) NOT NULL,
    quantity NUMERIC(19, 4) NOT NULL,
    CONSTRAINT uk_positions_portfolio_ticker UNIQUE (portfolio_id, ticker)
);

CREATE TABLE trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    trade_ref VARCHAR(255) NOT NULL,
    portfolio_id BIGINT NOT NULL,
    ticker VARCHAR(255) NOT NULL,
    trade_type VARCHAR(255) NOT NULL,
    quantity NUMERIC(19, 4) NOT NULL,
    price NUMERIC(19, 4) NOT NULL,
    status VARCHAR(255) NOT NULL,
    rejection_reason VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    settled_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_trades_trade_ref UNIQUE (trade_ref)
);

CREATE INDEX idx_trades_portfolio_id ON trades(portfolio_id);
CREATE INDEX idx_trades_status ON trades(status);
